from datetime import datetime
from typing import Self
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field, model_validator

from app.enums import Naics2dIndustryCode, TriageStatus


class BaseUUIDCreateModel(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: UUID
    created_at: datetime
    updated_at: datetime


class IntakeSubmissionCreate(BaseModel):
    """Payload for creating a new intake submission"""

    title: str = Field(min_length=1, max_length=255, description="Name or title of the project")
    description: str = Field(min_length=1, description="Brief overview of project and goals")
    start_datetime: datetime
    end_datetime: datetime
    industry: Naics2dIndustryCode
    budget_range: str = Field(min_length=1, max_length=64)

    @model_validator(mode="after")
    def end_after_start(self) -> Self:
        try:
            ends_first = self.end_datetime <= self.start_datetime
        except TypeError:
            raise ValueError("start_datetime and end_datetime must both include a timezone or neither")
        if ends_first:
            raise ValueError("end_datetime must be after start_datetime")
        return self


class IntakeSubmission(IntakeSubmissionCreate, BaseUUIDCreateModel):
    """An intake of a new initiative that tribe will be undertaking"""


class TriageResult(BaseModel):
    """What the LLM triager returns for a submission"""

    summary: str = Field(description="A summary of the project generated by our LLM triager")
    tags: list[str] | None = Field(
        default=None, description="A list of tags that will help us filter/search"
    )
    risk_checklist: str = Field(
        description="A set of bullet points that will describe the risks associated with this initiative"
    )


class IntakeSubmissionTriageRecord(BaseUUIDCreateModel):
    """
    This is where we store the results of our intake scoring of our individual
    submissions. The record exists from the moment a submission is created, so
    `status` tells a poller whether the LLM results are in yet.
    """

    intake_submission_id: UUID  # linking to our orig submission
    status: TriageStatus
    summary: str | None = None
    tags: list[str] | None = None
    risk_checklist: str | None = None
    error: str | None = None
